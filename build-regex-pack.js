#!/usr/bin/env node
// Builds both rule packs the options page inserts, so what it offers is always
// the same lines documented in the .txt files:
//
//   regex-pack.txt   -> ui/regex-pack.js   (window.UNVIX_REGEX_PACK)
//   exclude-pack.txt -> ui/exclude-pack.js (window.UNVIX_EXCLUDE_PACK)
//
// Run after editing either file:  node build-regex-pack.js
//
// Both packs are verified to compile. The extraction pack is additionally
// checked against the empty string: `while (regex.exec())` with the /g flag
// never advances lastIndex on an empty match, so a rule that can match "" would
// hang the service worker. The same test is meaningless for the exclude pack —
// a filter is only ever tested against a path — so it is not applied there.
const fs = require('fs');
const path = require('path');

function readRules(file) {
  return fs.readFileSync(path.join(__dirname, file), 'utf8')
    .split('\n').map(s => s.trim()).filter(Boolean);
}

function writePack(outName, varName, rules, comment) {
  const out = path.join(__dirname, 'ui', outName);
  const body = rules.map(r => '  ' + JSON.stringify(r)).join(',\n');
  fs.writeFileSync(out,
`// GENERATED by build-regex-pack.js from ${comment} — do not edit by hand.
// ${rules.length} rules, all verified to compile.
window.${varName} = [
${body}
];
`);
  console.log(`wrote ${out} (${rules.length} rules)`);
}

// --- extraction rules ---
const rules = readRules('regex-pack.txt');
rules.forEach(r => {
  let re;
  try { re = new RegExp(r, 'gi'); }
  catch (e) { throw new Error(`extraction rule does not compile: ${r}\n  ${e.message}`); }
  if (re.exec('') !== null) throw new Error(`extraction rule can match the empty string (would hang extractEndpoints): ${r}`);
});
writePack('regex-pack.js', 'UNVIX_REGEX_PACK', rules, 'regex-pack.txt');

// --- exclude rules (out of scope) ---
const excludes = readRules('exclude-pack.txt');
excludes.forEach(r => {
  try { new RegExp(r, 'i'); }
  catch (e) { throw new Error(`exclude rule does not compile: ${r}\n  ${e.message}`); }
});
writePack('exclude-pack.js', 'UNVIX_EXCLUDE_PACK', excludes, 'exclude-pack.txt');
